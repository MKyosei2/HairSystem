    derived_metric_id INTEGER PRIMARY KEY AUTOINCREMENT,
    run_id INTEGER,
    scope_type TEXT NOT NULL,
    scope_key TEXT NOT NULL,
    metric_name TEXT NOT NULL,
    metric_value REAL,
    units TEXT,
